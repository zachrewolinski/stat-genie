#!/bin/bash
#
# Setup script for Azure OpenAI Codex with Entra ID authentication.
# This script:
#   1. Creates the Codex config file (~/.codex/config.toml)
#   2. Refreshes the Azure Entra ID token
#   3. Exports AZURE_OPENAI_API_KEY
#
# Usage:
#   source scripts/setup-azure-codex.sh
#
# Prerequisites:
#   - Azure CLI installed and logged in (az login)
#   - Python azure-identity package (pip install azure-identity)
#   - Cognitive Services OpenAI User role on your Azure OpenAI resource

# ============================================================================
# CONFIGURATION - Update these values for your Azure setup
# ============================================================================

AZURE_RESOURCE_NAME="fxdata-eastus2"
AZURE_DEPLOYMENT_NAME="gpt-5.2-codex"

# Your Azure OpenAI resource name (the part before .openai.azure.com)
AZURE_RESOURCE_NAME="${AZURE_RESOURCE_NAME:-your-resource-name}"

# Your Azure OpenAI deployment name (NOT the model name)
AZURE_DEPLOYMENT_NAME="${AZURE_DEPLOYMENT_NAME:-your-deployment-name}"

# Azure API version
AZURE_API_VERSION="${AZURE_API_VERSION:-2025-04-01-preview}"

# Wire API: "responses" or "chat.completions"
AZURE_WIRE_API="${AZURE_WIRE_API:-responses}"

# ============================================================================
# Create Codex config
# ============================================================================

create_codex_config() {
    local config_dir="$HOME/.codex"
    local config_file="$config_dir/config.toml"
    
    mkdir -p "$config_dir"
    
    if [[ -f "$config_file" ]]; then
        echo "Backing up existing config to $config_file.bak"
        cp "$config_file" "$config_file.bak"
    fi
    
    cat > "$config_file" << EOF
# Codex CLI configuration for Azure OpenAI with Entra ID
# Generated by setup-azure-codex.sh

model_provider = "azure"
model = "$AZURE_DEPLOYMENT_NAME"

[model_providers.azure]
name = "Azure OpenAI"
base_url = "https://$AZURE_RESOURCE_NAME.openai.azure.com/openai"
query_params = { api-version = "$AZURE_API_VERSION" }
wire_api = "$AZURE_WIRE_API"
env_key = "AZURE_OPENAI_API_KEY"

[profiles.azure]
model_provider = "azure"
model = "$AZURE_DEPLOYMENT_NAME"
EOF

    echo "Created Codex config at $config_file"
}

# ============================================================================
# Refresh Azure Entra ID token
# ============================================================================

refresh_token() {
    echo "Refreshing Azure Entra ID token (via Azure CLI user)..."
    
    # Check if azure-identity is installed (non-fatal in local use)
    if ! python3 -c "import azure.identity" 2>/dev/null; then
        echo "Warning: azure-identity not installed. Run: pip install azure-identity"
        return 0
    fi

    # Get token using AzureCliCredential so we *only* use the
    # az login user identity, avoiding DefaultAzureCredential
    # picking up any other env/service-principal credentials.
    local token
    token=$(python3 << 'PYTHON'
from azure.identity import AzureCliCredential
import sys

scope = "https://cognitiveservices.azure.com/.default"

try:
    cred = AzureCliCredential()
    token = cred.get_token(scope).token
    print("USING_AZURE_CREDENTIAL:AzureCliCredential", file=sys.stderr)
    print(token)
except Exception as e:
    print(f"Error getting token: {e}", file=sys.stderr)
    # Do not propagate a non-zero exit code; keep this best-effort for local use.
PYTHON
)
    
    if [[ -z "$token" ]]; then
        echo "Warning: Failed to get token"
        return 0
    fi
    
    export AZURE_OPENAI_API_KEY="$token"
    echo "Token refreshed successfully (length: ${#AZURE_OPENAI_API_KEY})"
}

# ============================================================================
# Main
# ============================================================================

main() {
    echo "=== Azure Codex Setup ==="
    echo ""
    echo "Configuration:"
    echo "  Resource:   $AZURE_RESOURCE_NAME"
    echo "  Deployment: $AZURE_DEPLOYMENT_NAME"
    echo "  API Ver:    $AZURE_API_VERSION"
    echo "  Wire API:   $AZURE_WIRE_API"
    echo ""
    
    # Check if we need to create config
    if [[ ! -f "$HOME/.codex/config.toml" ]] || [[ "${FORCE_CONFIG:-}" == "1" ]]; then
        create_codex_config
    else
        echo "Codex config already exists at ~/.codex/config.toml"
        echo "Set FORCE_CONFIG=1 to overwrite"
    fi
    
    echo ""
    refresh_token
    
    echo ""
    echo "=== Setup Complete ==="
    echo ""
    echo "You can now run Codex:"
    echo "  npx codex --profile azure \"your prompt\""
    echo ""
    echo "Or run the agentic experiments:"
    echo "  bash scripts/analysis.sh caschools noperturb 1 codex"
}

# Run main if script is executed (not sourced)
# When sourced, just define the functions and export the token
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main
else
    # Script is being sourced - just refresh the token
    # Ensure a refresh failure doesn't kill the current shell/tmux session
    # due to 'set -e' at the top of this script.
    refresh_token || true
fi
