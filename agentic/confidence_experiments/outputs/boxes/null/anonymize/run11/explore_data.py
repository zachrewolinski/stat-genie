import pandas as pd


df = pd.read_csv('boxes.csv')
print('Shape:', df.shape)
print('\nHead:')
print(df.head())
print('\nDescribe:')
print(df.describe(include='all'))
print('\nValue counts for feature1 (outcome):')
print(df['feature1'].value_counts().sort_index())
print('\nValue counts for feature2 (gender):')
print(df['feature2'].value_counts().sort_index())
print('\nAge (feature3) summary by outcome:')
print(df.groupby('feature1')['feature3'].describe())
print('\nOutcome by site (feature5):')
print(pd.crosstab(df['feature5'], df['feature1'], normalize='index'))
print('\nOutcome by age quartile:')
age_bins = pd.qcut(df['feature3'], 4, duplicates='drop')
print(pd.crosstab(age_bins, df['feature1'], normalize='index'))
